import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { IaCEngine } from '../services/iacEngine.js';
import { PipelineEngine } from '../services/pipelineEngine.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const templatesDir = path.resolve(__dirname, '../templates');

export function handleExportBundle(req, res) {
  const terraformMain = IaCEngine.generateTerraform({ appName: 'paystream-api', region: 'us-east-1' });
  const k8sManifest = IaCEngine.generateKubernetesManifests({ appName: 'paystream-api' });
  const githubActions = PipelineEngine.generateGitHubActionsYaml('paystream-api');

  let prometheusYml = '';
  let alertRulesYml = '';
  try {
    prometheusYml = fs.readFileSync(path.join(templatesDir, 'monitoring/prometheus.yml'), 'utf-8');
    alertRulesYml = fs.readFileSync(path.join(templatesDir, 'monitoring/alert_rules.yml'), 'utf-8');
  } catch (e) {
    prometheusYml = '# Prometheus default config';
    alertRulesYml = '# Alert rules config';
  }

  const dockerfile = `# Multi-stage production container build
FROM node:22-alpine AS builder
WORKDIR /app
COPY package*.json ./
RUN npm ci
COPY . .
RUN npm run build --if-present

FROM node:22-alpine AS runner
WORKDIR /app
ENV NODE_ENV=production
COPY --from=builder /app/package*.json ./
RUN npm ci --omit=dev
COPY --from=builder /app/dist ./dist 2>/dev/null || COPY --from=builder /app ./
EXPOSE 8080
USER node
CMD ["node", "server/index.js"]
`;

  const bundle = {
    generatedAt: new Date().toISOString(),
    version: '1.0.0',
    platform: 'OpsAutomator SaaS',
    files: [
      { path: 'terraform/main.tf', content: terraformMain, description: 'AWS VPC, ALB, ASG & CloudWatch Terraform' },
      { path: 'k8s/deployment.yaml', content: k8sManifest, description: 'Zero-Downtime Rolling Update Kubernetes Manifest' },
      { path: '.github/workflows/deploy.yml', content: githubActions, description: 'Blue-Green GitHub Actions Pipeline' },
      { path: 'monitoring/prometheus.yml', content: prometheusYml, description: 'Prometheus Scrape Configuration' },
      { path: 'monitoring/alert_rules.yml', content: alertRulesYml, description: 'Prometheus & Alertmanager Alert Rules' },
      { path: 'Dockerfile', content: dockerfile, description: 'Multi-stage production Dockerfile' },
      { path: 'README.md', content: '# DevOps Automation Kit\nGenerated by OpsAutomator SaaS.\n\nRun `terraform init && terraform apply` to provision AWS infrastructure.', description: 'Deployment instructions' }
    ]
  };

  res.writeHead(200, {
    'Content-Type': 'application/json',
    'Content-Disposition': 'attachment; filename="opsautomator-production-kit.json"'
  });
  res.end(JSON.stringify(bundle, null, 2));
}

